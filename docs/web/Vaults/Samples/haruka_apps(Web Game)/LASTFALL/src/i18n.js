export function resolveLanguage(languages = [], saved = null) {
  if (saved === 'en' || saved === 'ja') return saved;
  for (const value of languages) {
    const base = String(value).toLowerCase().split(/[-_]/)[0];
    if (base === 'en' || base === 'ja') return base;
  }
  return 'en';
}

let preference = 'auto';
let language = 'en';
const cache = new Map();
const patterns = Object.keys(EN).filter((key) => key.includes('{')).map((key) => {
  const names = [...key.matchAll(/\{(\w+)\}/g)].map((match) => match[1]);
  const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return { key, names, regex: new RegExp('^' + escaped.replace(/\\\{\w+\\\}/g, '(.+?)') + '$') };
});

export function getLanguage() { return language; }
export function getLanguagePreference() { return preference; }

export function t(source, values, depth = 0) {
  const text = String(source ?? '');
  if (language === 'ja') return values ? text.replace(/\{(\w+)\}/g, (_, key) => values[key] ?? '') : text;
  if (values) return (EN[text] ?? text).replace(/\{(\w+)\}/g, (_, key) => t(values[key], undefined, depth + 1));
  if (Object.hasOwn(EN, text)) return EN[text];
  if (!/[ぁ-んァ-ン一-龥]/.test(text) || depth > 3) return text;
  if (cache.has(text)) return cache.get(text);
  let translated = text;
  for (const { key, names, regex } of patterns) {
    const match = regex.exec(text);
    if (!match) continue;
    const params = Object.fromEntries(names.map((name, index) => [name, match[index + 1]]));
    translated = t(key, params, depth + 1);
    break;
  }
  if (cache.size >= 256) cache.clear();
  cache.set(text, translated);
  return translated;
}

export function renderLanguage(root = document) {
  for (const element of root.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
  for (const element of root.querySelectorAll('[data-i18n-placeholder]')) element.placeholder = t(element.dataset.i18nPlaceholder);
  for (const element of root.querySelectorAll('[data-i18n-label]')) element.setAttribute('aria-label', t(element.dataset.i18nLabel));
  for (const select of root.querySelectorAll('[data-language]')) select.value = preference;
  document.documentElement.lang = language;
}

export function setLanguage(value = 'auto') {
  preference = ['en', 'ja'].includes(value) ? value : 'auto';
  try {
    if (preference === 'auto') localStorage.removeItem('lastfall_language');
    else localStorage.setItem('lastfall_language', preference);
  } catch { /* Private browsing and file URLs may disable storage. */ }
  language = resolveLanguage(navigator.languages?.length ? navigator.languages : [navigator.language], preference);
  cache.clear();
  renderLanguage();
  document.dispatchEvent(new Event('languagechange'));
}

export function initLanguage() {
  try { preference = localStorage.getItem('lastfall_language') || 'auto'; } catch { /* use browser preference */ }
  if (!['auto', 'en', 'ja'].includes(preference)) preference = 'auto';
  language = resolveLanguage(navigator.languages?.length ? navigator.languages : [navigator.language], preference);
  renderLanguage();
  document.addEventListener('change', (event) => {
    if (event.target.matches('[data-language]')) setLanguage(event.target.value);
  });
  window.addEventListener('languagechange', () => { if (preference === 'auto') setLanguage('auto'); });
}
